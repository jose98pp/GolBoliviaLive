import assert from 'node:assert/strict';
import { buildEventSourcesPatch, getDefaultSourceId, getEventSources, normalizeEventSources } from '../src/utils/eventSources';
import { probeHlsSource } from '../src/services/sourceProbe';
import type { LiveEvent } from '../src/types/football';
const raw = [{ id: 'source-a', name: 'Canal A', type: 'hls', url: 'http://example.test:8000/live/index.m3u8' }, { id: 'source-b', name: 'Canal B', type: 'hls', url: 'https://example.test/b.m3u8' }, { id: 'source-c', name: 'Canal iframe', type: 'iframe', url: '<iframe src="https://streamxhd.st/live1.php?stream=dsports"></iframe>' }];
const sources = normalizeEventSources(raw);
assert.equal(sources.length, 3); assert.equal(sources[2].url, 'https://streamxhd.st/live1.php?stream=dsports');
assert.equal(buildEventSourcesPatch(sources, 'source-b').iptvSource!.streamUrl, sources[1].url);
assert.equal(buildEventSourcesPatch(sources, 'source-c').primaryProvider, 'external');
assert.equal(buildEventSourcesPatch(sources, 'source-a').autoFailoverEnabled, false);
assert.throws(() => buildEventSourcesPatch(sources, 'missing'));
assert.throws(() => normalizeEventSources([...raw, raw[0]]));
assert.throws(() => normalizeEventSources([{ ...raw[0], url: 'javascript:alert(1)' }]));
assert.throws(() => normalizeEventSources(Array.from({ length: 21 }, (_, i) => ({ ...raw[0], id: `source-${i}` }))));
const legacy = { primaryProvider: 'external', externalSource: { url: sources[2].url }, cloudflare: { playbackUrl: 'https://example.test/live.m3u8' }, youtube: { videoId: 'jfKfPfyJRdk' } } as LiveEvent;
assert.equal(getEventSources(legacy).length, 3); assert.equal(getDefaultSourceId(legacy), 'legacy-external');
assert.deepEqual(getEventSources({ ...legacy, sources: [] }), [], 'Una lista vaciada no revive fuentes antiguas');
const originalFetch = globalThis.fetch;
const originalTimeout = globalThis.setTimeout;
const methods: string[] = [];
try {
  globalThis.fetch = (async (_url: any, options: any) => { methods.push(options.method || 'GET'); return new Response('#EXTM3U\n#EXT-X-TARGETDURATION:2\n'); }) as typeof fetch;
  assert.equal((await probeHlsSource(sources[1])).ok, true); assert.deepEqual(methods, ['GET'], 'Se crea/verifica el manifiesto con GET, sin depender de HEAD');
  globalThis.fetch = (async () => new Response('<html>not a stream</html>')) as typeof fetch;
  assert.equal((await probeHlsSource(sources[1])).ok, false);
  let calls = 0;
  globalThis.fetch = (async () => { calls++; return new Response('', { status: 404 }); }) as typeof fetch;
  await probeHlsSource(sources[1]); assert.equal(calls, 1, 'Un IPTV 404 no reintenta como si fuera un emisor propio');
  globalThis.setTimeout = ((callback: any, delay: any, ...args: any[]) => originalTimeout(callback, delay >= 1500 && delay <= 6000 ? 0 : delay, ...args)) as any;
  calls = 0;
  globalThis.fetch = (async () => { calls++; return calls < 3 ? new Response('', { status: 404 }) : new Response('#EXTM3U\n'); }) as typeof fetch;
  assert.equal((await probeHlsSource({ ...sources[1], waitForBroadcast: true })).ok, true); assert.equal(calls, 3);
  calls = 0;
  globalThis.fetch = (async () => { calls++; return new Response('', { status: 404 }); }) as typeof fetch;
  assert.equal((await probeHlsSource({ ...sources[1], waitForBroadcast: true })).ok, false); assert.equal(calls, 5, 'Un path inexistente termina tras cinco consultas');
  calls = 0;
  globalThis.fetch = (async () => { calls++; return new Response('', { status: 403 }); }) as typeof fetch;
  assert.equal((await probeHlsSource({ ...sources[1], waitForBroadcast: true })).ok, false); assert.equal(calls, 1);
} finally { globalThis.fetch = originalFetch; globalThis.setTimeout = originalTimeout; }
console.log('Fuentes: múltiples HLS/iframe, migración compatible, fuente inicial, validación, GET real de manifiesto, arranque MediaMTX y rechazo 403 comprobados.');
