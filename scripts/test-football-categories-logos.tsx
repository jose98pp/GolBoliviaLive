import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { FOOTBALL_COMPETITIONS, FOOTBALL_WOMENS, FOOTBALL_YOUTH, clubLeague } from '../src/data/footballLeagues';
import { footballCategory, footballImportClubId, findFootballImportClub } from '../src/utils/footballImports';
import { normalizeChannelLogoUrl } from '../src/utils/channelLogos';
import { ChannelLogo } from '../src/components/ChannelLogo';
import { getClubLeague } from '../src/utils/clubCrests';
import { BOLIVIAN_CLUBS } from '../src/data/bolivianFootballData';
import { parseChannelPlaylist } from '../src/utils/channelSources';
import type { Club } from '../src/types/football';

assert.equal(FOOTBALL_COMPETITIONS['mex.1'], 'México (Liga MX)');
assert.equal(FOOTBALL_COMPETITIONS['usa.1'], 'Estados Unidos (MLS)');
assert.equal(footballCategory('mex.women'), 'w');
assert.equal(footballCategory('fifa.world_u20_womens'), 'w20');
assert.equal(footballCategory('CONMEBOL Sudamericano Sub-17 masculino'), 'm17');
assert.equal(footballCategory('conmebol.sudamericano.sub20'), 'm20');
const male: Club = { ...BOLIVIAN_CLUBS.bolivar, id: 'espn_100', name: 'América', shortName: 'América', league: FOOTBALL_COMPETITIONS['mex.1'], country: 'México' };
const female: Club = { ...male, id: 'espn_w_200', league: FOOTBALL_WOMENS['mex.women'] };
const youth: Club = { ...male, id: 'espn_m20_300', league: `Internacionales · ${FOOTBALL_YOUTH['fifa.world_u20']}` };
assert.equal(findFootballImportClub({ male, female, youth }, undefined, ['América'], 'mex.1')?.id, male.id);
assert.equal(findFootballImportClub({ male, female, youth }, '200', ['América'], 'mex.women')?.id, female.id);
assert.equal(findFootballImportClub({ male, female, youth }, '300', ['América'], 'fifa.world_u20')?.id, youth.id);
assert.equal(findFootballImportClub({ male }, '200', ['América'], 'mex.women'), undefined, 'No reutiliza el masculino por coincidencia de nombre');
assert.notEqual(footballImportClubId('100', 'mex.women'), footballImportClubId('100', 'mex.1'));
assert.notEqual(footballImportClubId('100', 'fifa.world_u20'), footballImportClubId('100', 'fifa.world_u20_womens'));
assert.equal(clubLeague(female), FOOTBALL_WOMENS['mex.women']);
assert.equal(getClubLeague(female), 'mex.women');
assert.equal(getClubLeague({ country: 'US' }), 'usa.1');
assert.equal(getClubLeague({ country: 'México' }), 'mex.1');
for (const invalid of ['http://example.test/logo.png', 'javascript:alert(1)', 'data:image/svg+xml,test', '//example.test/logo.png', 'https://user:pass@example.test/logo.png']) assert.equal(normalizeChannelLogoUrl(invalid), '');
assert.equal(normalizeChannelLogoUrl(' https://example.test/logo.svg '), 'https://example.test/logo.svg');
assert.equal(normalizeChannelLogoUrl('/logos/espn.png'), '/logos/espn.png');
assert.doesNotMatch(renderToStaticMarkup(<ChannelLogo src="javascript:alert(1)" name="ESPN México" />), /<img/);
assert.match(renderToStaticMarkup(<ChannelLogo name="ESPN México" />), /Logo no disponible: ESPN México/);
assert.match(renderToStaticMarkup(<ChannelLogo src="https://example.test/logo.svg" name="ESPN" />), /src="https:\/\/example.test\/logo.svg"/);
const imported = parseChannelPlaylist('#EXTM3U\n#EXTINF:-1 tvg-logo="../logos/espn.png",ESPN\nhttps://cdn.example/live.m3u8', 'https://provider.example/lists/lista.m3u');
assert.equal(imported[0].logo, 'https://provider.example/logos/espn.png');
